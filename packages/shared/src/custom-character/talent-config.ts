/** 按分类ID查分类 */
export function findTalentCategory(categoryId: string): TalentCategory | undefined {
  return TALENT_CONFIG.find((c) => c.id === categoryId);
}

/** 按天赋名反查词条（含所属分类），用于校验和展示 */
export function findTalentByName(name: string): { category: TalentCategory; entry: TalentEntry } | undefined {
  for (const category of TALENT_CONFIG) {
    const entry = category.entries.find((e) => e.name === name);
    if (entry) return { category, entry };
  }
  return undefined;
}
